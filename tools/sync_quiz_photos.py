#!/usr/bin/env python3
"""Generate quiz photo metadata; image bytes load only when a quiz renders them."""
from pathlib import Path
import argparse,hashlib,json,re
ROOT=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
folder=ROOT/'app/assets/quiz-photos';sheets=json.loads((folder/'manifest.json').read_text())
for sheet in sheets.values():
    name=sheet['file']
    if not re.fullmatch(r'[A-Za-z0-9_-]+\.webp',name) or (folder/name).is_symlink():
        raise ValueError('Invalid quiz photo sheet filename')
    digest=hashlib.sha256((folder/name).read_bytes()).hexdigest()[:16]
    sheet['src']='assets/quiz-photos/'+name+'?v='+digest
    sheet.pop('source',None)
text='/* Generated by tools/sync_quiz_photos.py; metadata only; keep referenced sheets and manifest. */\nvar ClosetLintQuizPhotos='+json.dumps(sheets,separators=(',',':'))+';\n'
p=ROOT/'app/scripts/comfort-quiz-photos.js'
if args.check:
    if not p.exists() or p.read_text()!=text:raise SystemExit('Run python3 tools/sync_quiz_photos.py')
else:p.write_text(text)
